#!/usr/bin/env bash
# Releases, rolls back and inspects one environment.
#
#   bash deploy/stack.sh <env> release <version> [--ticket <n>]
#                                  deploy a version (images from deploy/build.sh)
#   bash deploy/stack.sh <env> rollback
#                                  back to the last good version before the current one
#   bash deploy/stack.sh <env> status [--wait] [--json]
#                                  5xx rate per endpoint since the last release;
#                                  --wait first waits until the observation window
#                                  after the last release has passed
#   bash deploy/stack.sh <env> history       releases and rollbacks, oldest first
#   bash deploy/stack.sh <env> version       version running now (empty if none)
#   bash deploy/stack.sh <env> ps | logs [service] | down | destroy
#
# <env> is dev, staging or prod. Settings come from deploy/env/<env>.env. The
# state lives outside the repository, one directory per environment under
# CV_DEPLOY_STATE_DIR (default ~/.config/cv-generator-deploy):
#   <env>/secrets   passwords, generated at the first start, random per environment
#   <env>/history   one line per release or rollback (tab-separated)
#   <env>/mcp-token bearer token of the deploy MCP server (deploy/mcp/start.sh)
#
# This script is the single implementation of release, status and rollback:
# the deploy MCP server (deploy/mcp) and people run the same commands.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

usage() { sed -n '2,24p' "$0"; }
(($# >= 2)) || { usage >&2; exit 2; }
env="$1"; action="$2"; shift 2
require_env "$env"

env_file="$deploy_dir/env/$env.env"
state_dir="$(state_dir_of "$env")"
secrets_file="$state_dir/secrets"
history_file="$state_dir/history"
lock_dir="$state_dir/lock"
project="cv-$env"
window="${CV_STATUS_WINDOW_SECONDS:-$(env_value "$env_file" STATUS_WINDOW_SECONDS)}"
max_rate="${CV_STATUS_MAX_5XX_RATE:-0.01}"
actor="${CV_DEPLOY_ACTOR:-operator}"

# --- Secrets ------------------------------------------------------------------
ensure_secrets() {
  local v value
  mkdir -p "$state_dir"
  ( umask 077
    [[ -f "$secrets_file" ]] || echo "# Generated by deploy/stack.sh for environment $env. Do not commit." > "$secrets_file"
    for v in POSTGRES_PASSWORD KEYCLOAK_DB_PASSWORD KEYCLOAK_ADMIN_PASSWORD CV_SYNTHETIC_CLIENT_SECRET; do
      grep -q "^$v=." "$secrets_file" && continue
      # Generated into a variable first: inside "echo $(...)" a failing
      # openssl would go unnoticed and leave an empty password.
      value="$(openssl rand -hex 24)" || die "cannot generate $v (openssl)"
      [[ ${#value} -eq 48 ]] || die "cannot generate $v (openssl)"
      sed -i "/^$v=\$/d" "$secrets_file"
      echo "$v=$value" >> "$secrets_file"
    done ) || exit 1
}

compose() {
  "${compose_cmd[@]}" -p "$project" \
    -f "$(native_path "$deploy_dir/compose.yaml")" \
    --env-file "$(native_path "$env_file")" \
    --env-file "$(native_path "$secrets_file")" "$@"
}

container_of() { compose ps -q "$1" 2>/dev/null | head -n 1; }

running_version() {
  local id
  id="$(CV_VERSION=none container_of api)"
  [[ -n "$id" ]] || return 0
  "$engine" inspect --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$id"
}

# --- History ------------------------------------------------------------------
# Columns: id kind version previous started finished finished_epoch outcome ticket actor
history_header=$'id\tkind\tversion\tprevious\tstarted\tfinished\tfinished_epoch\toutcome\tticket\tactor'

record() { # kind version previous started outcome ticket
  local now id
  now="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  id="$env-$(date -u +%Y%m%dT%H%M%SZ)-$2"
  [[ -f "$history_file" ]] || echo "$history_header" > "$history_file"
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$id" "$1" "$2" "${3:--}" "$4" "$now" "$(date -u +%s)" "$5" "${6:--}" "$actor" >> "$history_file"
  echo "$id"
}

# The version to roll back to: the most recent successful entry whose version
# is neither the current one nor one that was already rolled back from.
rollback_target() {
  local current="$1"
  [[ -f "$history_file" ]] || return 0
  awk -F'\t' -v cur="$current" '
    NR == 1 { next }
    { kind[NR] = $2; ver[NR] = $3; prev[NR] = $4; out[NR] = $8; n = NR }
    $2 == "rollback" && $8 == "ok" { bad[$4] = 1 }
    END {
      for (i = n; i > 1; i--)
        if (out[i] == "ok" && ver[i] != cur && !(ver[i] in bad)) { print ver[i]; exit }
    }' "$history_file"
}

last_finished_epoch() {
  [[ -f "$history_file" ]] || { echo 0; return; }
  awk -F'\t' 'NR > 1 && $8 == "ok" { e = $7 } END { print e + 0 }' "$history_file"
}

# One release or rollback at a time per environment (mkdir is atomic).
lock() {
  mkdir "$lock_dir" 2>/dev/null \
    || die "$env: another release or rollback is running (if not, remove the directory $lock_dir)"
  trap 'rmdir "$lock_dir" 2>/dev/null || true' EXIT
}

require_images() {
  local name
  for name in "${release_components[@]}"; do
    image_exists "$(image_name "$name" "$1")" \
      || die "image $(image_name "$name" "$1") not found: run bash deploy/build.sh $1"
  done
}

deploy_version() { # version: true if every service ends up healthy
  CV_VERSION="$1" compose up -d --wait --wait-timeout "${CV_DEPLOY_TIMEOUT:-300}" >&2
}

# --- Status -------------------------------------------------------------------
metrics() {
  local web
  web="$(CV_VERSION=none container_of web)"
  [[ -n "$web" ]] || die "$env: nothing is running"
  # From inside the environment network: the management port is not published.
  "$engine" exec "$web" wget -q -O - http://api:8081/actuator/prometheus
}

# Prometheus text -> one line per endpoint: uri requests errors_5xx
per_endpoint() {
  awk '
    /^http_server_requests_seconds_count\{/ {
      uri = $0; sub(/.*uri="/, "", uri); sub(/".*/, "", uri)
      st = $0; sub(/.*status="/, "", st); sub(/".*/, "", st)
      if (uri ~ /^\/actuator/) next
      total[uri] += $NF
      if (st ~ /^5/) err[uri] += $NF
    }
    END { for (u in total) printf "%s %d %d\n", u, total[u], err[u] + 0 }' | sort
}

status() {
  local wait=0 json=0 arg released now until rows breached=false
  for arg in "$@"; do
    case "$arg" in --wait) wait=1 ;; --json) json=1 ;; *) die "status: unknown option $arg" ;; esac
  done
  released="$(last_finished_epoch)"
  now="$(date -u +%s)"
  until=$((released + window))
  if ((wait && now < until)); then
    log "$env: waiting $((until - now)) s (window of $window s after the last release)"
    sleep $((until - now))
  fi
  rows="$(metrics | per_endpoint)"
  if [[ -n "$rows" ]] && awk -v max="$max_rate" '$2 > 0 && $3 / $2 > max { found = 1 } END { exit !found }' <<<"$rows"; then
    breached=true
  fi
  if ((json)); then
    awk -v env="$env" -v ver="$(running_version)" -v rel="$released" -v win="$window" \
        -v max="$max_rate" -v br="$breached" '
      BEGIN { printf "{\"environment\":\"%s\",\"version\":\"%s\",\"releasedAtEpoch\":%d,\"windowSeconds\":%d,\"max5xxRate\":%s,\"breached\":%s,\"endpoints\":[", env, ver, rel, win, max, br }
      NF == 3 { printf "%s{\"endpoint\":\"%s\",\"requests\":%d,\"errors5xx\":%d,\"rate5xx\":%.4f}", (n++ ? "," : ""), $1, $2, $3, ($2 ? $3 / $2 : 0) }
      END { print "]}" }' <<<"$rows"
  else
    echo "environment $env, version $(running_version), 5xx threshold $max_rate"
    printf '%-24s %10s %10s %10s\n' endpoint requests 5xx rate
    awk 'NF == 3 { printf "%-24s %10d %10d %9.2f%%\n", $1, $2, $3, ($2 ? 100 * $3 / $2 : 0) }' <<<"$rows"
    echo "breached: $breached"
  fi
}

# --- Actions ------------------------------------------------------------------
ensure_secrets
case "$action" in
  release)
    version="${1:?release needs a version (see deploy/build.sh)}"; shift
    ticket=""
    [[ "${1:-}" == --ticket ]] && ticket="${2:?--ticket needs a number}"
    [[ "$version" =~ ^[0-9a-f]{12}$ ]] || die "invalid version '$version' (12 hex characters)"
    require_images "$version"
    lock
    previous="$(running_version)"
    started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    log "$env: releasing $version (running: ${previous:-nothing})"
    if deploy_version "$version"; then
      id="$(record release "$version" "$previous" "$started" ok "$ticket")"
      log "$env: $version is live on http://localhost:$(env_value "$env_file" WEB_PORT)"
      echo "$id"
    else
      record release "$version" "$previous" "$started" failed "$ticket" >/dev/null
      die "$env: $version did not become healthy; the environment needs a rollback"
    fi
    ;;
  rollback)
    lock
    current="$(running_version)"
    target="$(rollback_target "$current")"
    [[ -n "$target" ]] || die "$env: no earlier good version to roll back to (running: ${current:-nothing})"
    require_images "$target"
    started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    log "$env: rolling back ${current:-nothing} -> $target"
    if deploy_version "$target"; then
      record rollback "$target" "$current" "$started" ok >/dev/null
      log "$env: $target is live again"
      echo "$target"
    else
      record rollback "$target" "$current" "$started" failed >/dev/null
      die "$env: rollback to $target did not become healthy"
    fi
    ;;
  status)  status "$@" ;;
  history) [[ -f "$history_file" ]] && cat "$history_file" || true ;;
  version) running_version ;;
  ps)      CV_VERSION=none compose ps ;;
  logs)    CV_VERSION=none compose logs --no-color "$@" ;;
  down)    CV_VERSION=none compose down ;;
  destroy) CV_VERSION=none compose down --volumes ;;
  *) usage >&2; exit 2 ;;
esac
