#!/usr/bin/env bash
# Starts, stops and inspects one environment.
#
#   bash deploy/stack.sh <env> up <version>    deploy that version (images from deploy/build.sh)
#   bash deploy/stack.sh <env> version         version running now (empty if none)
#   bash deploy/stack.sh <env> ps              containers and their health
#   bash deploy/stack.sh <env> logs [service]  logs
#   bash deploy/stack.sh <env> down            stop; the database volume is kept
#   bash deploy/stack.sh <env> destroy         stop and delete the database volume too
#
# <env> is dev, staging or prod. Settings come from deploy/env/<env>.env;
# passwords from <secrets dir>/<env>.secrets, generated at the first start:
# outside the repository, random, different for every environment.
# Secrets dir: CV_DEPLOY_SECRETS_DIR, default ~/.config/cv-generator-deploy.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

usage() { sed -n '2,16p' "$0"; }
(($# >= 2)) || { usage >&2; exit 2; }
env="$1"; action="$2"; shift 2
require_env "$env"

env_file="$deploy_dir/env/$env.env"
secrets_dir="${CV_DEPLOY_SECRETS_DIR:-$HOME/.config/cv-generator-deploy}"
secrets_file="$secrets_dir/$env.secrets"
project="cv-$env"

ensure_secrets() {
  [[ -f "$secrets_file" ]] && return 0
  mkdir -p "$secrets_dir"
  ( umask 077
    { echo "# Generated by deploy/stack.sh for environment $env. Do not commit."
      for v in POSTGRES_PASSWORD KEYCLOAK_DB_PASSWORD KEYCLOAK_ADMIN_PASSWORD; do
        echo "$v=$(openssl rand -hex 24)"
      done
    } > "$secrets_file" )
  log "generated passwords for $env in $secrets_file"
}

compose() {
  "${compose_cmd[@]}" -p "$project" \
    -f "$(native_path "$deploy_dir/compose.yaml")" \
    --env-file "$(native_path "$env_file")" \
    --env-file "$(native_path "$secrets_file")" "$@"
}

running_version() {
  local id
  id="$(compose ps -q api 2>/dev/null | head -n 1)"
  [[ -n "$id" ]] || return 0
  "$engine" inspect --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$id"
}

ensure_secrets
case "$action" in
  up)
    version="${1:?up needs a version (see deploy/build.sh)}"
    for name in api web; do
      image_exists "$(image_name "$name" "$version")" \
        || die "image $(image_name "$name" "$version") not found: run bash deploy/build.sh $version"
    done
    log "$env: deploying $version (was: $(running_version || true))"
    CV_VERSION="$version" compose up -d --wait --wait-timeout "${CV_DEPLOY_TIMEOUT:-300}" >&2
    log "$env: $version is up on http://localhost:$(env_value "$env_file" WEB_PORT)"
    ;;
  version) running_version ;;
  ps)      CV_VERSION=none compose ps ;;
  logs)    CV_VERSION=none compose logs --no-color "$@" ;;
  down)    CV_VERSION=none compose down ;;
  destroy) CV_VERSION=none compose down --volumes ;;
  *) usage >&2; exit 2 ;;
esac
